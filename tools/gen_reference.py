"""Build docs/guide/reference/cli.md and mcp.md from the code: the argparse parsers and mcp_server.SPECS.

    python tools/gen_reference.py          # write both pages
    python tools/gen_reference.py --check  # exit 1 if a page is out of date
"""
import argparse
import runpy
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / 'docs/guide/reference'
HEADER = '<!-- Generated by tools/gen_reference.py from the code. Do not edit by hand. -->\n\n'
# Order of the CLI page: the start-here commands first, as `cg --help` groups them.
GROUPS = (
    ('Start here', ('start', 'locate', 'search', 'impact', 'verify', 'review')),
    ('Explore', ('find', 'show', 'callers', 'callees', 'path', 'context', 'source', 'map', 'flows', 'architecture',
                 'features', 'prepare', 'explore', 'export')),
    ('Index and maintenance', ('index', 'stats', 'check', 'dead', 'catalog', 'selftest')),
    ('Agents', ('mcp', 'change')),
)


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def arguments(parser):
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.option_strings:
            name = ', '.join(f'`{flag}`' for flag in action.option_strings)
            if action.nargs != 0:
                name += f' `{action.metavar or action.dest.upper()}`'
        else:
            name = f'`{action.metavar or action.dest}`' + (' (optional)' if action.nargs == '?' else '')
        default = action.default
        if isinstance(default, str) and default.startswith(str(Path.home())):
            default = '~' + default[len(str(Path.home())):]  # the machine's home folder is not part of the docs
        empty = default is None or default is False or default == [] or default is argparse.SUPPRESS
        shown = '' if empty or action.nargs == 0 else f'`{default}`'
        if action.required and action.option_strings:
            shown = 'required'
        choices = ''
        if action.choices is not None:
            values = list(action.choices)
            choices = f'{values[0]}–{values[-1]}' if isinstance(action.choices, range) else ', '.join(map(str, values))
        rows.append(f"| {name} | {cell(action.help or '')} | {shown} | {cell(choices)} |")
    if not rows:
        return 'No options.\n'
    return '| Argument | Meaning | Default | Values |\n|---|---|---|---|\n' + '\n'.join(rows) + '\n'


def usage(parser):
    text = parser.format_usage().replace('usage: ', '', 1).strip()
    return '```text\n' + ' '.join(text.split()) + '\n```\n'


def cli_page():
    cg = runpy.run_path(str(REPO / 'scripts/cg.py'))
    change = runpy.run_path(str(REPO / 'scripts/change_flow.py'))['build_parser']()
    parser = cg['build_parser']()
    sub = next(action for action in parser._actions if isinstance(action, argparse._SubParsersAction))
    listed = [name for _, names in GROUPS for name in names]
    missing = sorted(set(sub.choices) - set(listed))
    if missing:
        raise SystemExit('gen_reference: commands missing from GROUPS: ' + ', '.join(missing))
    out = [HEADER, '# CLI reference\n\n',
           'Every command runs on the project given by `--root` (default: the current folder), written before the '
           'command name: `cg --root ~/code/shop impact cancel_order`. `cg COMMAND --help` prints the same text.\n\n',
           'Values in **Default** apply when the option is left out. The JSON answers of the main commands are '
           'described in [Formats](formats.md).\n\n']
    for title, names in GROUPS:
        out.append(f'- **{title}:** ' + ' · '.join(f'[`{name}`](#{name})' for name in names) + '\n')
    for title, names in GROUPS:
        out.append(f'\n## {title}\n')
        for name in names:
            command = sub.choices[name]
            out.append(f'\n### {name}\n\n{command.description}\n\n')
            if name == 'change':
                out.append(usage(change).replace('cg change', 'cg [--root ROOT] change', 1) + '\n')
                actions = next(a for a in change._actions if isinstance(a, argparse._SubParsersAction))
                helps = {a.dest: a.help for a in actions._choices_actions}
                out.append('| Action | What it does |\n|---|---|\n')
                out += [f'| [`{action}`](#change-{action}) | {cell(helps[action])} |\n' for action in actions.choices]
                for action, command in actions.choices.items():
                    out.append(f'\n#### change {action}\n\n{helps[action][0].upper() + helps[action][1:]}.\n\n')
                    out.append(usage(command).replace('cg change', 'cg [--root ROOT] change', 1) + '\n')
                    out.append(arguments(command))
                continue
            out.append(usage(command).replace('cg ', 'cg [--root ROOT] ', 1) + '\n')
            out.append(arguments(command))
    return ''.join(out)


def mcp_page():
    specs = runpy.run_path(str(REPO / 'scripts/mcp_server.py'))['SPECS']
    out = [HEADER, '# MCP reference\n\n',
           f'`cg mcp` serves {len(specs)} tools over stdio. None of them edits or runs project code: `cg_index` '
           'writes only the graph cache, `cg_read` reads lines inside the project and every other tool runs the '
           'CLI command named in its section. The project is the one the server was started for; clients never '
           'choose the root or the command. '
           'Setup for Codex and Claude Code is in [Agents and MCP](../guides/agents-and-mcp.md).\n\n',
           '| Tool | What it answers |\n|---|---|\n']
    out += [f'| [`{name}`](#{name}) | {cell(spec[1])} |\n' for name, spec in specs.items()]
    for name, (command, description, properties, required) in specs.items():
        runs = 'Reads numbered lines directly; there is no CLI command.' if command == 'read' else f'Runs `cg {command}`.'
        out.append(f'\n## {name}\n\n{description}\n\n{runs}\n\n')
        if not properties:
            out.append('No parameters.\n')
            continue
        out.append('| Parameter | Type | Required | Default | Limits |\n|---|---|---|---|---|\n')
        for key, schema in properties.items():
            limits = [f'{label} {schema[key2]}' for key2, label in (('minimum', 'min'), ('maximum', 'max'),
                      ('minLength', 'min length'), ('maxLength', 'max length')) if key2 in schema]
            if 'enum' in schema:
                limits.append(', '.join(schema['enum']))
            default = f"`{str(schema['default']).lower() if isinstance(schema['default'], bool) else schema['default']}`" \
                if 'default' in schema else ''
            kind = schema.get('type', '')
            kind = ' or '.join(kind) if isinstance(kind, list) else kind
            if kind == 'array' and 'items' in schema:
                kind = f"array of {schema['items'].get('type', '')}"
            if 'maxItems' in schema:
                limits.append(f"at most {schema['maxItems']} items")
            out.append(f"| `{key}` | {kind} | {'yes' if key in required else ''} | {default} | "
                       f"{cell('; '.join(limits))} |\n")
    return ''.join(out)


def main():
    check = '--check' in sys.argv[1:]
    stale = []
    for name, text in (('cli.md', cli_page()), ('mcp.md', mcp_page())):
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        raise SystemExit('Out of date, run python tools/gen_reference.py: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
